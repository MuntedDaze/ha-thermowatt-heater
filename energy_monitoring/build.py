"""Generate the Home Assistant package and dashboard from ``entity_map.yaml``.

    python energy_monitoring/build.py            # rewrite energy_monitoring/generated/
    python energy_monitoring/build.py --check    # fail if generated/ is out of date
    python energy_monitoring/build.py --map my_map.yaml --out some/dir

Writes files only. It never talks to Home Assistant.
"""

import argparse
from pathlib import Path
import sys

import yaml

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from energy_monitoring.dashboard import build_dashboard  # noqa: E402
from energy_monitoring.mapping import DEFAULT_MAP, HERE, load  # noqa: E402
from energy_monitoring.package import build_package  # noqa: E402

GENERATED = HERE / "generated"
PACKAGE_FILE = "packages/thermann_energy.yaml"
DASHBOARD_FILE = "dashboards/energy.yaml"
BANNER = (
    "# GENERATED by energy_monitoring/build.py from entity_map.yaml. Do not edit:\n"
    "# change the map and regenerate. Read-only monitoring; commands nothing.\n"
)


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def _text(dumper, value):
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _text)


def dump(data: dict) -> str:
    return BANNER + yaml.dump(
        data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=10000
    )


def render(map_path: Path = DEFAULT_MAP) -> dict[str, str]:
    config = load(map_path)
    return {
        PACKAGE_FILE: dump(build_package(config)),
        DASHBOARD_FILE: dump(build_dashboard(config)),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--map", type=Path, default=DEFAULT_MAP)
    parser.add_argument("--out", type=Path, default=GENERATED)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for name, text in render(args.map).items():
        target = args.out / name
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(name)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target}")
    if stale:
        print("out of date: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
