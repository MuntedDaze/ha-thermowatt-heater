"""Closed-loop synthetic days through the real planner chain: reproducible results.

The saved report must be regenerated by tools/replay_shadow_days.py exactly, and
its comfort/cycle/cost outcomes must keep the owner's priorities: comfort first,
solar second, cost third. Synthetic only; no HA, cloud or heater access.
"""

import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).parents[1]


@pytest.fixture(scope="module")
def days():
    spec = importlib.util.spec_from_file_location(
        "day_replay_test", ROOT / "tools/replay_shadow_days.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module, module.report()


def test_saved_day_report_reproduces_exactly(days):
    module, fresh = days
    saved = json.loads(
        (ROOT / "shadow_controller/DAY_SCENARIO_RESULTS.json").read_text(encoding="utf-8")
    )
    assert json.loads(json.dumps(fresh)) == saved
    markdown = (ROOT / "shadow_controller/DAY_SCENARIO_RESULTS.md").read_text(encoding="utf-8")
    assert markdown.replace("\r\n", "\n") == module.markdown(fresh)
    assert saved["physical_heater_operations"] == saved["cloud_requests"] == 0


def test_comfort_first_outcomes(days):
    _, data = days
    rows = data["rows"]
    impossible = {"insufficient_off_peak_time"}
    for name, row in rows.items():
        if name in impossible:
            assert row["comfort_met"] is False
            assert ("14:00", "insufficient_time") in [tuple(item) for item in row["decisions"]]
        else:
            assert row["comfort_met"] is True, name
        assert row["cycles"] <= 2, name  # no cloud-driven switching storms
        assert row["cost_aud"] <= row["same_energy_all_grid_aud"] + 1e-9, name
    # Failed sunshine forecast still reaches comfort through the reserved fallback.
    failed = rows["forecast_sun_fails"]
    assert "begin_grid_fallback" in [code for _, code in failed["decisions"]]
    # Stale forecasts are never used to wait for solar.
    assert all(code != "wait_for_forecast_solar" for _, code in rows["stale_forecast"]["decisions"])


def test_solar_second_partial_surplus_and_stability(days):
    _, data = days
    rows = data["rows"]
    # With a qualified forecast, ~2 kW partial surplus starts long before fallback
    # and costs less than the measured-only default, which waits for fallback.
    assert rows["surplus_2kw_forecast"]["first_start"] < "12:00"
    assert rows["partial_2kw_measured_only"]["first_start"] > "14:00"
    assert rows["surplus_2kw_forecast"]["cost_aud"] < rows["partial_2kw_measured_only"]["cost_aud"]
    # More surplus means cheaper heating and an earlier start.
    costs = [rows[f"surplus_{kw}kw_forecast"]["cost_aud"] for kw in (2, 3, 4)]
    assert costs == sorted(costs, reverse=True)
    # A 30-minute cloud is ridden through: one cycle, grace period visible.
    drop = rows["solar_drop_mid_cycle"]
    assert drop["cycles"] == 1
    assert "heat_now_grace_period" in [code for _, code in drop["decisions"]]
    # Ignoring its own 3 kW load does not make the stateful policy oscillate,
    # but the decision then misreports solar as partial: de-embedding is needed.
    naive = rows["no_deembedding_naive_meter"]
    assert naive["cycles"] == 1
    assert "heat_now_partial_solar" in [code for _, code in naive["decisions"]]
    # A cloud-poll outage suspends; a fresh poll restarts without losing comfort.
    outage = rows["cloud_poll_outage"]
    assert "data_unavailable" in [code for _, code in outage["decisions"]]
    assert outage["comfort_met"] and outage["cycles"] == 2


def test_morning_threshold_and_dst_days(days):
    _, data = days
    rows = data["rows"]
    assert rows["warm_morning_tank"]["energy_kwh"] == 0
    for name in ("cold_morning_tank", "dst_start_morning", "dst_end_morning"):
        row = rows[name]
        assert row["comfort"][0]["deadline"].endswith("07:00") and row["comfort"][0]["met"]
        assert row["solar_kwh"] == 0 and row["first_start"] == "05:53"
    assert rows["target_65"]["energy_kwh"] < rows["target_70"]["energy_kwh"]
